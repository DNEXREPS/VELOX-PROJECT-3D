/**
 * Generates supabase/seed.sql from supabase/catalog/*.json.
 *   npm run db:seed:build
 * The demo catalogue is clearly labelled (verification_status = 'demo').
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { z } from "zod";
import { catalogCategorySchema, catalogFileSchema } from "../src/lib/validation/catalog";
import { categoriesSql, catalogSql } from "./catalog-sql";

const root = join(import.meta.dirname, "..");
const categories = z.array(catalogCategorySchema).parse(JSON.parse(readFileSync(join(root, "supabase/catalog/categories.json"), "utf8")));
const demo = catalogFileSchema.parse(JSON.parse(readFileSync(join(root, "supabase/catalog/demo-catalog.json"), "utf8")));

const known = new Set(categories.map((c) => c.slug));
for (const c of demo.components) {
  if (!known.has(c.category)) throw new Error(`Unknown category ${c.category} in ${c.slug}`);
  if (c.verification_status && c.verification_status !== "demo") throw new Error(`Demo catalogue entry ${c.slug} must be demo`);
}

const sql = `-- =============================================================================
-- VELOX Digital Garage — seed data (GENERATED by scripts/build-seed.ts; do not edit)
--
-- 1. Component categories (reference data, required).
-- 2. DEMO component catalogue: fictional sample parts, verification_status = 'demo'.
--    These are NOT manufacturer specifications. Import real, sourced data with
--    \`npm run catalog:import -- <file.json>\`.
-- =============================================================================

${categoriesSql(categories)}
-- ---------------------------------------------------------------------------
-- DEMO catalogue (${demo.components.length} components)
-- ---------------------------------------------------------------------------
${catalogSql(demo, { defaultVerification: "demo", specSource: "demo" })}`;

writeFileSync(join(root, "supabase/seed.sql"), sql);
console.log(`Wrote supabase/seed.sql (${categories.length} categories, ${demo.components.length} demo components)`);
